#!/usr/bin/env node
// Build step — inlines everything the site renders into site/data.js:
//   plan       data/plan.json
//   index      data/summary/index.json
//   summaries  data/summary/<week>.json
//   reports    data/reports/<week>.json        (optional, on-demand debriefs)
//   course     data/refs/course.json           (profile + sections)
//   editions   data/refs/editions.json         (past-edition analysis)
//   paceModel  data/refs/pace-model.json       (personal grade->pace curve)
// data.js is the ONLY copy the site reads (works from file:// and http alike),
// regenerated on every build, so it can't go stale. Gate C check-4 parses it
// back and deep-compares against data/. Exit 0 = built, 2 = failed.

import { readFileSync, writeFileSync, statSync, existsSync } from "node:fs";

const OUT = "site/data.js";

function readJSON(path) {
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch (e) {
    console.error(`inline-data: cannot read/parse ${path}: ${e.message}`);
    process.exit(2);
  }
}

export function collect() {
  const plan = readJSON("data/plan.json");
  const index = existsSync("data/summary/index.json") ? readJSON("data/summary/index.json") : { weeks: [] };
  if (!Array.isArray(index.weeks)) {
    console.error("inline-data: data/summary/index.json has no weeks array");
    process.exit(2);
  }
  const summaries = {};
  for (const week of index.weeks) summaries[week] = readJSON(`data/summary/${week}.json`);

  const reports = {};
  if (existsSync("data/reports/index.json")) {
    const ri = readJSON("data/reports/index.json");
    if (!Array.isArray(ri.weeks)) {
      console.error("inline-data: data/reports/index.json has no weeks array");
      process.exit(2);
    }
    for (const week of ri.weeks) reports[week] = readJSON(`data/reports/${week}.json`);
  }

  return {
    plan, index, summaries, reports,
    course: readJSON("data/refs/course.json"),
    editions: readJSON("data/refs/editions.json"),
    paceModel: readJSON("data/refs/pace-model.json"),
  };
}

const isMain = process.argv[1] && process.argv[1].replace(/\\/g, "/").endsWith("scripts/build/inline-data.mjs");
if (isMain) {
  const data = collect();
  const banner =
    "/* Generated by scripts/build/inline-data.mjs from data/. Do not edit by hand. */\n";
  try {
    writeFileSync(OUT, `${banner}window.XM_DATA = ${JSON.stringify(data)};\n`);
  } catch (e) {
    console.error(`inline-data: cannot write ${OUT}: ${e.message}`);
    process.exit(2);
  }
  console.log(`inline-data: ${OUT} ${statSync(OUT).size} B (${data.index.weeks.length} weeks, ${Object.keys(data.reports).length} reports)`);
}
